"""Record hashes of a freshly resolved, Windows CPython 3.13 wheel set."""
from email.parser import BytesParser
import hashlib
from pathlib import Path
import zipfile

root = Path(__file__).resolve().parents[2]
lines = []
for wheel in (root / "build" / "windows-wheels").glob("*.whl"):
    with zipfile.ZipFile(wheel) as package:
        metadata = BytesParser().parsebytes(package.read(next(name for name in package.namelist() if name.endswith(".dist-info/METADATA"))))
    with wheel.open("rb") as stream:
        digest = hashlib.file_digest(stream, "sha256").hexdigest()
    lines.append(f"{metadata['Name']}=={metadata['Version']} --hash=sha256:{digest}")
if not lines:
    raise SystemExit("First download runtime-requirements.in wheels to build/windows-wheels using Python 3.13 x64 on Windows.")
(Path(__file__).parent / "runtime-requirements.lock").write_text("# Windows x64 / CPython 3.13 only. Generated by lock.py from PyPI wheels.\n" + "\n".join(sorted(lines, key=str.lower)) + "\n", encoding="utf-8")
print(f"Locked {len(lines)} wheels.")
